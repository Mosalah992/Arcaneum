import fs from 'node:fs';
import path from 'node:path';

const libraryDir = path.resolve('content/library');
const migrationDir = path.resolve('migrations');

// 0013 already repaired Songs of the Return.
// 0014 will repair the remaining books.
const migrationNumber = '0014';
const migrationName = 'repair_volume_headings';
const migrationPath = path.join(
  migrationDir,
  `${migrationNumber}_${migrationName}.sql`,
);

/*
 * These are the books identified as having malformed multi-volume
 * headings in the current library.
 *
 * The replacements are deliberately explicit. We do NOT globally
 * replace every occurrence of "Volume", "Part", etc., because those
 * words can legitimately occur inside ordinary prose.
 */
const repairs = {
  'AR-II-005': [
    {
      from: /^Nightingales,\s*Volume\s*II\s*$/m,
      to: '## Nightingales, Volume II',
    },
  ],

  'AR-VI-001': [
    {
      from: /^Cicero’s Journal:\s*Volume\s*2\s*$/m,
      to: '## Cicero’s Journal: Volume 2',
    },
    {
      from: /^Cicero’s Journal:\s*Volume\s*3\s*$/m,
      to: '## Cicero’s Journal: Volume 3',
    },
    {
      from: /^Cicero’s Journal:\s*Volume\s*4\s*$/m,
      to: '## Cicero’s Journal: Volume 4',
    },
    {
      from: /^Cicero’s Journal,\s*The Final Volume\s*$/m,
      to: '## Cicero’s Journal, The Final Volume',
    },
  ],

  'AR-VI-008': [
    {
      from: /^Rising Threat,\s*Vol\.\s*II\s*$/m,
      to: '## Rising Threat, Vol. II',
    },
    {
      from: /^Rising Threat,\s*Vol\.\s*III\s*$/m,
      to: '## Rising Threat, Vol. III',
    },
    {
      from: /^Rising Threat,\s*Vol\.\s*IV\s*$/m,
      to: '## Rising Threat, Vol. IV',
    },
  ],

  'AR-VII-005': [
    {
      from: /^Report:\s*Disaster at Ionith,\s*Part\s*II\s*$/m,
      to: '## Report: Disaster at Ionith, Part II',
    },
    {
      from: /^Report:\s*Disaster at Ionith,\s*Part\s*III\s*$/m,
      to: '## Report: Disaster at Ionith, Part III',
    },
    {
      from: /^Report:\s*Disaster at Ionith,\s*Part\s*IV\s*$/m,
      to: '## Report: Disaster at Ionith, Part IV',
    },
  ],

  'AR-VIII-010': [
    {
      from: /^Volume\s*2\s*$/m,
      to: '## Volume 2',
    },
  ],
};

// ------------------------------------------------------------
// Helpers
// ------------------------------------------------------------

function findBookFile(callNumber) {
  const files = fs
    .readdirSync(libraryDir)
    .filter((file) => file.endsWith('.md'));

  for (const file of files) {
    const fullPath = path.join(libraryDir, file);
    const markdown = fs.readFileSync(fullPath, 'utf8');

    const match = markdown.match(
      /^call_number:\s*([^\r\n]+)$/m,
    );

    if (match?.[1].trim() === callNumber) {
      return {
        file,
        path: fullPath,
        markdown,
      };
    }
  }

  return null;
}

function removeFrontmatter(markdown) {
  return markdown
    .replace(/^---\s*\n[\s\S]*?\n---\s*\n/, '')
    .trim();
}

function escapeSql(value) {
  return value.replaceAll("'", "''");
}

// ------------------------------------------------------------
// Repair Markdown files
// ------------------------------------------------------------

const repairedBooks = [];

for (const [callNumber, replacements] of Object.entries(repairs)) {
  const book = findBookFile(callNumber);

  if (!book) {
    throw new Error(
      `Could not find Markdown file for call number ${callNumber}`,
    );
  }

  let markdown = book.markdown;
  let changed = false;

  for (const { from, to } of replacements) {
    if (from.test(markdown)) {
      markdown = markdown.replace(from, to);
      changed = true;
    }
  }

  if (!changed) {
    console.log(`⚪ ${callNumber}: no changes needed`);
    continue;
  }

  fs.writeFileSync(book.path, markdown, 'utf8');

  repairedBooks.push({
    callNumber,
    file: book.file,
    body: removeFrontmatter(markdown),
  });

  console.log(`✅ ${callNumber}: repaired ${book.file}`);
}

// ------------------------------------------------------------
// Generate migration
// ------------------------------------------------------------

if (repairedBooks.length === 0) {
  console.log('\nNo Markdown files required repair.');
  process.exit(0);
}

const statements = repairedBooks.map(({ callNumber, file, body }) => {
  return `-- ${callNumber} (${file})
UPDATE tomes
SET body = '${escapeSql(body)}'
WHERE call_number = '${escapeSql(callNumber)}';`;
});

const sql = `-- Repair malformed multi-volume headings
-- Generated by scripts/repair-volume-headings.mjs
--
-- This migration updates only the affected tomes.
-- It does not modify search.ts or other library records.

${statements.join('\n\n')}
`;

fs.mkdirSync(migrationDir, { recursive: true });
fs.writeFileSync(migrationPath, sql, 'utf8');

console.log('');
console.log(`Created migration: ${migrationPath}`);
console.log(`Books repaired: ${repairedBooks.length}`);
console.log('');
console.log('Books included:');

for (const { callNumber, file } of repairedBooks) {
  console.log(`  ${callNumber} -> ${file}`);
}